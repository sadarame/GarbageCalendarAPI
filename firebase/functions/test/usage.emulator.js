const test=require('node:test');
const assert=require('node:assert/strict');
if (!process.env.FIRESTORE_EMULATOR_HOST) throw new Error('Emulator required');
const {initializeApp,deleteApp}=require('firebase-admin/app');
const {getFirestore}=require('firebase-admin/firestore');
const {saveShared,searchShared,resetUserData,collectionName,cell}=require('../lib/shared');
const app=initializeApp({projectId:'demo-garbage-usage'}),db=getFirestore(app);
const base={name:'人数テスト',latitude:35.68,longitude:139.76,rules:[{garbageType:'燃えるゴミ',schedule:'毎週',yobi:'月曜日'}]};
const count=async id=>(await searchShared(db,base)).result.find(x=>x.No===id)?.usageCount;
test('保存・再送・同時保存・変更・初期化・公開予定の移管',async()=>{
 for(const id of ['a','b']) await db.collection(collectionName).doc(id).set({...base,status:'published',cell:cell(base.latitude,base.longitude)});
 assert.equal(await count('a'),'0');
 await saveShared(db,'alice',{...base,selectedScheduleId:'a'});
 await saveShared(db,'alice',{...base,selectedScheduleId:'a'});
 assert.equal(await count('a'),'1');
 await Promise.all(['bob','carol'].map(uid=>saveShared(db,uid,{...base,selectedScheduleId:'a'})));
 assert.equal(await count('a'),'3');
 await saveShared(db,'alice',{...base,selectedScheduleId:'b'});
 assert.equal(await count('a'),'2');assert.equal(await count('b'),'1');
 await assert.rejects(saveShared(db,'alice',{...base,selectedScheduleId:'missing'}));
 assert.equal(await count('b'),'1');
 await resetUserData(db,'alice');await resetUserData(db,'alice');
 assert.equal(await count('b'),'0');
 assert.equal((await db.collection('v2SharedUsageSelections').doc('alice').get()).exists,false);
 const own=await saveShared(db,'owner',base);
 await saveShared(db,'follower',{...base,selectedScheduleId:own.id});
 assert.equal(await count(own.id),'2');
 const key=(await db.collection(collectionName).doc(own.id).get()).data().usageKey;
 await resetUserData(db,'owner');
 const retained=(await db.collection(collectionName).where('usageKey','==',key).get()).docs[0].id;
 assert.equal(await count(retained),'1');
 await saveShared(db,'follower',{...base,selectedScheduleId:'b'});
 assert.equal(await count(retained),'0');assert.equal(await count('b'),'1');
});
test.after(async()=>{await db.terminate();await deleteApp(app);});
